"""`prompteval bootstrap`: an AI-drafted dataset and scorers, for you to review (#20).

One model call reads your prompt and returns *data*: example inputs (or, with
a seed file, expectations for your real inputs), which hard rules the prompt
states, and a rubric for the subjective part. prompteval then writes the files
itself from fixed templates using the stock scorers, so **no AI-written code
is ever executed**: the rubric is embedded as a string literal, and per-example
expectations live in dataset.jsonl.

Guardrails:
- Every file starts with a DRAFT marker; `run` warns until you delete it,
  and deleting it is your acceptance.
- Generated inputs are marked `"source": "synthetic"`, and `compare` says how
  many examples are synthetic. Seeded inputs stay `"real"`.
- The generator model is named in BOOTSTRAP.md; evaluate (and judge) with a
  different one, so the model is not grading tests it wrote.
- The cost is estimated and shown before the call; existing files are never
  overwritten without --force.
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from prompteval.cost import ModelPricing, UnknownModelError, Usage, compute_cost, resolve_pricing

DRAFT_MARKER = "# PROMPTEVAL-DRAFT"
DRAFT_LINE = (
    f"{DRAFT_MARKER}: generated by `prompteval bootstrap`. Review it, then delete this line."
)
DEFAULT_GENERATOR = "gpt-4.1-mini"
DEFAULT_EVAL_MODEL = "gpt-4o-mini"
MAX_EXAMPLES = 100

SYSTEM = (
    "You design evaluation sets for an LLM prompt. You return JSON only, matching the "
    "requested shape exactly. You never include personal data."
)

SHAPE = """Return a JSON object with exactly these keys:
{
  "examples": [
    {"input": "<what a user would send>", "category": "typical" | "edge" | "adversarial",
     "must_mention": ["<phrase a good reply must contain>", ...],
     "required_keys": ["<JSON key a good reply must have>", ...],
     "min_len": <int or null>, "max_len": <int or null>}
  ],
  "checks": {"must_mention": <bool>, "json_keys": <bool>, "length": <bool>},
  "rule_sources": {"must_mention": "<quote from the prompt or empty>",
                   "json_keys": "<quote or empty>", "length": "<quote or empty>"},
  "judge_rubric": "<instructions for a judge model rating ONE reply from 0 to 1 on the
                   subjective qualities the prompt asks for; end with: Reply with only a number
                   between 0 and 1.>",
  "notes": "<2-4 sentences: what you assumed and what the user should check first>"
}
Turn on a check only when the prompt itself states that rule. Leave lists empty when a
check is off."""


@dataclass
class Draft:
    examples: list[dict[str, Any]]
    checks: dict[str, bool]
    rule_sources: dict[str, str]
    judge_rubric: str
    notes: str
    generator: str
    usage: Usage = field(default_factory=lambda: Usage(prompt_tokens=0, completion_tokens=0))
    reported_cost: float | None = None  # when the provider reports it (Claude Code)


def _request(prompt_text: str, n: int, seed_inputs: list[str] | None) -> str:
    if seed_inputs:
        task = (
            "Use EXACTLY these real inputs, in this order, one example each, and do not "
            "invent others. Fill in what a good reply to each must contain:\n"
            + json.dumps(seed_inputs, ensure_ascii=False)
        )
    else:
        task = (
            f"Write {n} examples a real user might send: about 60% typical, 25% edge cases, "
            "15% adversarial (attempts to make the assistant break its instructions)."
        )
    return f"The prompt under test:\n<<<\n{prompt_text}\n>>>\n\n{task}\n\n{SHAPE}"


def estimate_cost(
    prompt_text: str, n: int, model: str, prices: dict[str, ModelPricing] | None = None
) -> float | None:
    """A rough upper estimate of the generator call, before making it."""
    try:
        pricing = resolve_pricing(model, prices)
    except UnknownModelError:
        return None
    prompt_tokens = (len(_request(prompt_text, n, None)) + len(SYSTEM)) // 3
    completion_tokens = 400 + 120 * n
    return compute_cost(
        model, Usage(prompt_tokens=prompt_tokens, completion_tokens=completion_tokens), pricing
    ).total_cost


def _strings(value: Any, limit: int = 12) -> list[str]:
    if not isinstance(value, list):
        return []
    return [str(v)[:200] for v in value if isinstance(v, (str, int, float)) and str(v).strip()][
        :limit
    ]


def _length(value: Any) -> int | None:
    return int(value) if isinstance(value, (int, float)) and 0 < value < 100_000 else None


def generate(
    prompt_text: str,
    *,
    client: Any,
    n: int = 25,
    model: str = DEFAULT_GENERATOR,
    seed_inputs: list[str] | None = None,
) -> Draft:
    """Ask the generator for a draft and validate every field it returns."""
    response = client.chat.completions.create(
        model=model,
        messages=[
            {"role": "system", "content": SYSTEM},
            {"role": "user", "content": _request(prompt_text, n, seed_inputs)},
        ],
        response_format={"type": "json_object"},
        temperature=0.4,
    )
    try:
        raw = json.loads(response.choices[0].message.content or "")
    except json.JSONDecodeError as err:
        raise ValueError(
            f"The generator did not return JSON ({err}); try again or another --model."
        ) from err
    if not isinstance(raw, dict) or not isinstance(raw.get("examples"), list):
        raise ValueError(
            "The generator's reply has no 'examples' list; try again or another --model."
        )

    examples = []
    for item in raw["examples"][: (len(seed_inputs) if seed_inputs else min(n, MAX_EXAMPLES))]:
        if not isinstance(item, dict) or not str(item.get("input", "")).strip():
            continue
        category = (
            item.get("category")
            if item.get("category") in {"typical", "edge", "adversarial"}
            else "typical"
        )
        examples.append(
            {
                "input": str(item["input"])[:4000],
                "category": category,
                "must_mention": _strings(item.get("must_mention")),
                "required_keys": _strings(item.get("required_keys")),
                "min_len": _length(item.get("min_len")),
                "max_len": _length(item.get("max_len")),
            }
        )
    if seed_inputs:
        # Keep the user's real inputs verbatim, whatever the generator echoed back.
        examples = [{**ex, "input": real} for ex, real in zip(examples, seed_inputs, strict=False)]
    if not examples:
        raise ValueError("The generator returned no usable examples; try again or another --model.")

    checks_value = raw.get("checks")
    checks_raw: dict[str, Any] = checks_value if isinstance(checks_value, dict) else {}
    checks = {k: bool(checks_raw.get(k)) for k in ("must_mention", "json_keys", "length")}
    sources_value = raw.get("rule_sources")
    sources_raw: dict[str, Any] = sources_value if isinstance(sources_value, dict) else {}
    rubric = str(raw.get("judge_rubric") or "").strip()[:3000] or (
        "Rate how well this reply follows the assistant's instructions and helps the user, "
        "from 0 (not at all) to 1 (fully). Reply with only a number between 0 and 1."
    )
    usage_obj = getattr(response, "usage", None)
    return Draft(
        examples=examples,
        checks=checks,
        rule_sources={k: str(sources_raw.get(k) or "")[:300] for k in checks},
        judge_rubric=rubric,
        notes=str(raw.get("notes") or "").strip()[:1500],
        generator=model,
        usage=Usage(
            prompt_tokens=int(getattr(usage_obj, "prompt_tokens", 0) or 0),
            completion_tokens=int(getattr(usage_obj, "completion_tokens", 0) or 0),
        ),
        reported_cost=(
            float(response.reported_cost_usd)
            if isinstance(getattr(response, "reported_cost_usd", None), (int, float))
            else None
        ),
    )


def _dataset_rows(draft: Draft, seeded_ids: list[str] | None) -> list[dict[str, Any]]:
    rows = []
    for i, ex in enumerate(draft.examples):
        expected: dict[str, Any] = {}
        if draft.checks["must_mention"] and ex["must_mention"]:
            expected["must_mention"] = ex["must_mention"]
        if draft.checks["json_keys"] and ex["required_keys"]:
            expected["required_keys"] = ex["required_keys"]
        if draft.checks["length"]:
            if ex["min_len"] is not None:
                expected["min_len"] = ex["min_len"]
            if ex["max_len"] is not None:
                expected["max_len"] = ex["max_len"]
        rows.append(
            {
                "id": seeded_ids[i] if seeded_ids else f"draft-{i + 1:02d}",
                "input": ex["input"],
                "expected": expected,
                "vars": {"category": ex["category"]},
                "source": "real" if seeded_ids else "synthetic",
            }
        )
    return rows


def _eval_py(
    draft: Draft, eval_model: str, base_url: str | None = None, judge_model: str | None = None
) -> str:
    stock = []
    if draft.checks["must_mention"]:
        stock.append("mentions_required_terms")
    if draft.checks["json_keys"]:
        stock.append("json_schema_valid")
    if draft.checks["length"]:
        stock.append("length_between")
    imports = f"from prompteval.eval.stock import {', '.join(stock)}\n" if stock else ""
    if base_url == "claude-code":
        imports += "from prompteval.providers.claude_code import ClaudeCodeClient\n"
        judge_setup = (
            "# Runs through your local Claude Code (no API key); the judge is a\n"
            "# different model from the one being evaluated.\n"
            f"JUDGE_MODEL = {json.dumps(judge_model or 'claude-sonnet-5-5')}\n"
            "_judge_client = ClaudeCodeClient()\n"
        )
        judge_args = ", model=JUDGE_MODEL, client=_judge_client"
        base_url_line = '\n    base_url="claude-code",'
    else:
        judge_setup = ""
        judge_args = ""
        base_url_line = f"\n    base_url={json.dumps(base_url)}," if base_url else ""
    scorers = ", ".join([*stock, "follows_instructions"])
    return f'''{DRAFT_LINE}
"""Draft eval written by `prompteval bootstrap` (generator: {draft.generator}).

Every check below is a suggestion. Read BOOTSTRAP.md, keep what measures what
you care about, delete the rest, then delete the DRAFT line at the top.
"""

from pathlib import Path

from prompteval import Eval, llm_judge, scorer
{imports}
{judge_setup}
# The judge rubric, as drafted from your prompt. Edit freely.
RUBRIC = {json.dumps(draft.judge_rubric)}


@scorer
def follows_instructions(output: str) -> float:
    """LLM judge for the subjective parts of the prompt (tone, helpfulness)."""
    return llm_judge(rubric=RUBRIC, text=output{judge_args})


eval = Eval(
    name="bootstrapped",
    dataset=str(Path(__file__).parent / "dataset.jsonl"),
    scorers=[{scorers}],
    model={json.dumps(eval_model)},{base_url_line}
)
'''


def _notes_md(draft: Draft, cost: float | None, n_rows: int, seeded: bool) -> str:
    def line(check: str, label: str, scorer: str) -> str:
        if not draft.checks[check]:
            return f"- **{label}**: not used (the prompt does not state this rule)."
        src = draft.rule_sources.get(check) or "(no quote given; check it)"
        return f'- **{label}** → `{scorer}`, because the prompt says: "{src}"'

    cost_text = "unpriced" if cost is None else f"${cost:.4f}"
    origin = "your real inputs (expectations drafted)" if seeded else "synthetic inputs (drafted)"
    return f"""{DRAFT_LINE}

# What `prompteval bootstrap` drafted

- Generator: **{draft.generator}** (cost {cost_text}). Evaluate and judge with a
  *different* model, so no model grades tests it wrote.
- Dataset: {n_rows} examples from {origin}, tagged typical / edge / adversarial
  in `vars.category`.

## Checks, and where each came from

{line("must_mention", "Required phrases", "mentions_required_terms")}
{line("json_keys", "JSON keys", "json_schema_valid")}
{line("length", "Length limits", "length_between")}
- **Subjective quality** → `follows_instructions`, an LLM judge with the rubric in `eval.py`.

## The generator's notes

{draft.notes or "(none)"}

## Before your first real run

1. Read ten examples in `dataset.jsonl`: are these things your users send?
2. Check each `must_mention` list: would a good reply always say that?
3. Read the rubric in `eval.py`: is that what you mean by a good reply?
4. Delete the DRAFT line at the top of all three files.
"""


def write_files(
    draft: Draft,
    out_dir: Path,
    *,
    cost: float | None,
    eval_model: str = DEFAULT_EVAL_MODEL,
    seeded_ids: list[str] | None = None,
    force: bool = False,
    base_url: str | None = None,
    judge_model: str | None = None,
) -> list[Path]:
    paths = [out_dir / "dataset.jsonl", out_dir / "eval.py", out_dir / "BOOTSTRAP.md"]
    existing = [p for p in paths if p.exists()]
    if existing and not force:
        raise FileExistsError(
            f"{', '.join(map(str, existing))} already exist; pass --force to replace them"
        )
    out_dir.mkdir(parents=True, exist_ok=True)
    rows = _dataset_rows(draft, seeded_ids)
    paths[0].write_text(
        DRAFT_LINE + "\n" + "".join(json.dumps(r, ensure_ascii=False) + "\n" for r in rows),
        encoding="utf-8",
    )
    paths[1].write_text(_eval_py(draft, eval_model, base_url, judge_model), encoding="utf-8")
    paths[2].write_text(_notes_md(draft, cost, len(rows), bool(seeded_ids)), encoding="utf-8")
    return paths


def has_draft_marker(path: Path) -> bool:
    try:
        with path.open(encoding="utf-8") as f:
            return f.readline().startswith(DRAFT_MARKER)
    except OSError:
        return False
